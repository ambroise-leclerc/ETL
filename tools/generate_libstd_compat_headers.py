#!/usr/bin/env python3
"""Generate (or check) the deprecated libstd/include/<header> compatibility wrappers.

Canonical standard headers live in libstd/include/c++/v1. Each header that used to be
reachable as <libstd/include/X> keeps a generated wrapper at that old path, which warns
and includes the canonical header by a relative quoted path. The wrappers are removed in
release 0.3.

Usage:
    generate_libstd_compat_headers.py          rewrite the wrappers
    generate_libstd_compat_headers.py --check  fail on missing, extra or stale wrappers
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEGACY_DIR = ROOT / "libstd" / "include"
CANONICAL_DIR = LEGACY_DIR / "c++" / "v1"

MANIFEST = (
    "algorithm", "array", "bitset", "cassert", "cctype", "cerrno", "cfenv", "cfloat", "chrono", "climits",
    "clocale", "cstddef", "cstdint", "exception", "functional", "initializer_list", "iterator", "limits",
    "memory", "new", "queue", "random", "ratio", "stdexcept", "string", "string_view", "thread", "tuple",
    "type_traits", "utility", "vector",
)

TEMPLATE = """\
// Generated by tools/generate_libstd_compat_headers.py - do not edit.
// Deprecated bridge to the canonical header, removed in release 0.3.
#pragma once

#if defined(_MSC_VER) && !defined(__clang__)
#pragma message("warning: <libstd/include/{name}> is deprecated, include <{name}> from libstd/include/c++/v1 instead")
#else
#warning "<libstd/include/{name}> is deprecated, include <{name}> from libstd/include/c++/v1 instead"
#endif

#include "c++/v1/{name}"
"""


def expected_wrappers():
    return {LEGACY_DIR / name: TEMPLATE.format(name=name) for name in MANIFEST}


def legacy_files():
    return {p for p in LEGACY_DIR.iterdir() if p.is_file()}


def check():
    errors = []
    wrappers = expected_wrappers()
    for path, content in sorted(wrappers.items()):
        if not (CANONICAL_DIR / path.name).is_file():
            errors.append(f"no canonical header for manifest entry {path.name}")
        if not path.is_file():
            errors.append(f"missing wrapper {path.relative_to(ROOT)}")
        elif path.read_text() != content:
            errors.append(f"stale wrapper {path.relative_to(ROOT)}")
    for path in sorted(legacy_files() - set(wrappers)):
        errors.append(f"extra file {path.relative_to(ROOT)}")
    for path in sorted(p for p in CANONICAL_DIR.iterdir() if p.is_file() and p.name not in MANIFEST):
        errors.append(f"canonical header {path.relative_to(ROOT)} is not in the manifest")
    for error in errors:
        print(error, file=sys.stderr)
    return 1 if errors else 0


def generate():
    for path, content in expected_wrappers().items():
        path.write_text(content)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare without rewriting files")
    return check() if parser.parse_args().check else generate()


if __name__ == "__main__":
    sys.exit(main())
